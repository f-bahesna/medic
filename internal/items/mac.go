// The macOS list of locations, as plain data: it builds on any system, so the
// README screenshot shows the real labels.

// macCleanableDirs returns the only folders whose contents medic will ever
// delete. Exact matches only.
func macCleanableDirs(home string) []string {
	L, AS := filepath.Join(home, "Library"), filepath.Join(home, "Library", "Application Support")
	return []string{
		filepath.Join(L, "Caches"),
		filepath.Join(L, "Logs"),
		filepath.Join(L, "Containers/com.apple.mail/Data/Library/Mail Downloads"),
		filepath.Join(AS, "Code/Cache"),
		filepath.Join(AS, "Code/CachedData"),
		filepath.Join(AS, "Code/CachedExtensionVSIXs"),
		filepath.Join(AS, "Cursor/Cache"),
		filepath.Join(AS, "Cursor/CachedData"),
		filepath.Join(AS, "Slack/Cache"),
		filepath.Join(AS, "Slack/Service Worker/CacheStorage"),
		filepath.Join(AS, "discord/Cache"),
		filepath.Join(L, "Developer/Xcode/DerivedData"),
		filepath.Join(L, "Developer/Xcode/iOS DeviceSupport"),
		filepath.Join(L, "Developer/CoreSimulator/Caches"),
		filepath.Join(home, ".yarn/berry/cache"),
		filepath.Join(home, ".bun/install/cache"),
		filepath.Join(home, ".cargo/registry/cache"),
		filepath.Join(home, ".cargo/registry/src"),
		filepath.Join(home, ".gradle/caches"),
		filepath.Join(home, ".m2/repository"),
	}
}

// MacItems lists the known locations on a Mac. has says whether a tool is
// installed; conda and photos are the package caches and Photos libraries
// that exist.
func MacItems(home string, has func(string) bool, conda, photos []string) []*Item {
	L, AS := filepath.Join(home, "Library"), filepath.Join(home, "Library", "Application Support")
	var list []*Item

	add(&list, Item{ID: "user_caches", Safety: Safe, Label: "User app caches",
		Note: "Apps rebuild these on demand. Quit apps before cleaning.", Cleanable: true, Paths: []string{filepath.Join(L, "Caches")}})
	add(&list, Item{ID: "user_logs", Safety: Safe, Label: "User logs",
		Note: "Diagnostic logs, only useful when debugging a problem.", Cleanable: true, Paths: []string{filepath.Join(L, "Logs")}})
	add(&list, Item{ID: "trash", Safety: Safe, Label: "Trash",
		Note: "Things you already deleted. Emptying the Trash is permanent.", Cleanable: true, Paths: []string{filepath.Join(home, ".Trash")}})
	add(&list, Item{ID: "mail_downloads", Safety: Safe, Label: "Mail attachment copies",
		Note: "Copies of attachments you opened. Originals stay in your mailbox.", Cleanable: true,
		Paths: []string{filepath.Join(L, "Containers/com.apple.mail/Data/Library/Mail Downloads")}})
	add(&list, Item{ID: "electron_caches", Safety: Safe, Label: "Desktop app web caches (VS Code, Cursor, Slack, Discord)",
		Note: "Quit these apps before cleaning.", Cleanable: true, Paths: []string{
			filepath.Join(AS, "Code/Cache"), filepath.Join(AS, "Code/CachedData"), filepath.Join(AS, "Code/CachedExtensionVSIXs"),
			filepath.Join(AS, "Cursor/Cache"), filepath.Join(AS, "Cursor/CachedData"),
			filepath.Join(AS, "Slack/Cache"), filepath.Join(AS, "Slack/Service Worker/CacheStorage"), filepath.Join(AS, "discord/Cache")}})

	add(&list, Item{ID: "xcode_derived", Safety: Safe, Label: "Xcode DerivedData",
		Note: "Build intermediates. The next build is slower, nothing is lost.", Cleanable: true,
		Paths: []string{filepath.Join(L, "Developer/Xcode/DerivedData")}})
	add(&list, Item{ID: "xcode_device_support", Safety: Safe, Label: "Xcode iOS DeviceSupport",
		Note: "Debug symbols per iOS version, copied again when a device connects.", Cleanable: true,
		Paths: []string{filepath.Join(L, "Developer/Xcode/iOS DeviceSupport")}})
	add(&list, Item{ID: "sim_caches", Safety: Safe, Label: "iOS Simulator caches",
		Note: "Regenerated by the simulator.", Cleanable: true, Paths: []string{filepath.Join(L, "Developer/CoreSimulator/Caches")}})
	add(&list, Item{ID: "sim_devices", Safety: Caution, Label: "iOS Simulator devices",
		Note: "Clean only deletes simulators whose iOS runtime is no longer installed.", Cleanable: has("xcrun"),
		Paths: []string{filepath.Join(L, "Developer/CoreSimulator/Devices")}})
	add(&list, Item{ID: "xcode_archives", Safety: Review, Label: "Xcode Archives",
		Note:  "Needed to symbolicate crash reports. Delete old ones in Xcode > Organizer.",
		Paths: []string{filepath.Join(L, "Developer/Xcode/Archives")}})

	add(&list, Item{ID: "npm", Safety: Safe, Label: "npm cache", Note: "Packages are downloaded again when needed.",
		Cleanable: has("npm"), Paths: []string{filepath.Join(home, ".npm/_cacache")}})
	add(&list, Item{ID: "pnpm", Safety: Safe, Label: "pnpm store",
		Note: "Clean runs 'pnpm store prune', which only drops packages no project uses.", Cleanable: has("pnpm"),
		Paths: []string{filepath.Join(L, "pnpm/store")}})
	add(&list, Item{ID: "yarn", Safety: Safe, Label: "Yarn Berry cache", Note: "Packages are downloaded again when needed.",
		Cleanable: true, Paths: []string{filepath.Join(home, ".yarn/berry/cache")}})
	add(&list, Item{ID: "bun", Safety: Safe, Label: "Bun cache", Note: "Packages are downloaded again when needed.",
		Cleanable: true, Paths: []string{filepath.Join(home, ".bun/install/cache")}})
	add(&list, Item{ID: "go_mod", Safety: Safe, Label: "Go module cache", Note: "Modules are downloaded again when needed.",
		Cleanable: has("go"), Paths: []string{filepath.Join(home, "go/pkg/mod")}})
	add(&list, Item{ID: "cargo", Safety: Safe, Label: "Cargo registry cache", Note: "Crates are downloaded again when needed.",
		Cleanable: true, Paths: []string{filepath.Join(home, ".cargo/registry/cache"), filepath.Join(home, ".cargo/registry/src")}})
	add(&list, Item{ID: "gradle", Safety: Safe, Label: "Gradle caches", Note: "Dependencies are downloaded again. Stop Gradle daemons first.",
		Cleanable: true, Paths: []string{filepath.Join(home, ".gradle/caches")}})
	if len(conda) > 0 {
		add(&list, Item{ID: "conda", Safety: Safe, Label: "Conda package cache",
			Note: "Clean runs 'conda clean --all', environments are kept.", Cleanable: has("conda"), Paths: conda})
	}
	add(&list, Item{ID: "maven", Safety: Caution, Label: "Maven local repository",
		Note: "Also holds artifacts you built with 'mvn install', which are not re-downloadable.", Cleanable: true,
		Paths: []string{filepath.Join(home, ".m2/repository")}})
	add(&list, Item{ID: "docker", Safety: Caution, Label: "Docker Desktop disk image",
		Note:      "Clean runs 'docker system prune': stopped containers, dangling images, build cache. Volumes are kept.",
		Cleanable: has("docker"), Paths: []string{filepath.Join(L, "Containers/com.docker.docker/Data/vms")}})

	add(&list, Item{ID: "podman", Safety: Review, Label: "Podman machine (VM disk)",
		Note:  "Holds your images and volumes. Run 'podman system prune', or 'podman machine rm' if unused.",
		Paths: []string{filepath.Join(home, ".local/share/containers/podman/machine")}})
	add(&list, Item{ID: "colima", Safety: Review, Label: "Colima VM",
		Note:  "Holds your images and volumes. Run 'docker system prune', or 'colima delete' if unused.",
		Paths: []string{filepath.Join(home, ".colima")}})
	add(&list, Item{ID: "android_avd", Safety: Review, Label: "Android emulators",
		Note: "Delete emulators you no longer use in Android Studio > Device Manager.", Paths: []string{filepath.Join(home, ".android/avd")}})
	add(&list, Item{ID: "android_images", Safety: Review, Label: "Android system images",
		Note: "Uninstall unused API levels in Android Studio > SDK Manager.", Paths: []string{filepath.Join(L, "Android/sdk/system-images")}})

	add(&list, Item{ID: "downloads", Safety: Review, Label: "Downloads folder",
		Note: "Your files. Sort by size in Finder and remove what you no longer need.", Paths: []string{filepath.Join(home, "Downloads")}})
	add(&list, Item{ID: "ios_backups", Safety: Review, Label: "iPhone / iPad backups",
		Note: "Delete old backups in Finder > your device > Manage Backups, never by hand.", Paths: []string{filepath.Join(AS, "MobileSync/Backup")}})
	add(&list, Item{ID: "messages", Safety: Review, Label: "Messages attachments",
		Note: "Review in System Settings > General > Storage > Messages.", Paths: []string{filepath.Join(L, "Messages/Attachments")}})
	for _, lib := range photos {
		add(&list, Item{ID: "photos", Safety: Review, Label: fmt.Sprintf("Photos library (%s)", filepath.Base(lib)),
			Note: "Never delete files inside it. Use the Photos app or iCloud 'Optimize Mac Storage'.", Paths: []string{lib}})
	}

	return list
}

// MacInstallers is the item for installer files found in Downloads and on the
// Desktop, with their total size.
func MacInstallers(files []string, total int64) *Item {
	return &Item{ID: "installers", Safety: Caution, Label: fmt.Sprintf("Installer files (%d .dmg/.pkg/.xip/.iso)", len(files)),
		Note: "Rarely needed after installing. Clean moves them to the Trash, so it can be undone.", Cleanable: true,
		Files: files, Bytes: total, Measured: true}
}

// DescribeMac fills in the commands that clean each item by hand. They mirror
// Clean; for folders only allowlisted ones with contents are listed, because
// zsh errors on a glob with no matches.
func DescribeMac(list []*Item, home string, hasContent func(string) bool) {
	allowed := macCleanableDirs(home)
	for _, it := range list {
		it.Commands = nil
		switch it.ID {
		case "trash":
			it.Commands = []string{`osascript -e 'tell application "Finder" to empty trash'`}
		case "sim_devices":
			it.Commands = []string{"xcrun simctl delete unavailable"}
		case "npm", "pnpm", "go_mod", "conda", "docker":
			it.Commands = []string{strings.Join(macToolCommand(it.ID), " ")}
		case "installers":
			// A list of single files, moved to the Trash by clean only.
		default:
			for _, p := range it.Paths {
				if contains(allowed, p) && hasContent(p) {
					it.Commands = append(it.Commands, fmt.Sprintf(`rm -rf "$HOME%s"/*`, strings.TrimPrefix(p, home)))
				}
			}
		}
	}
}

func macToolCommand(id string) []string {
	return map[string][]string{
		"npm":    {"npm", "cache", "clean", "--force"},
		"pnpm":   {"pnpm", "store", "prune"},
		"go_mod": {"go", "clean", "-modcache"},
		"conda":  {"conda", "clean", "--all", "--yes"},
		"docker": {"docker", "system", "prune", "--force"},
	}[id]
}
